BEGIN;

CREATE TABLE notice (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content TEXT NOT NULL CHECK (CHAR_LENGTH(TRIM(content)) > 0),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    published_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (expires_at IS NULL OR expires_at > published_at)
);
CREATE INDEX idx_notice_published ON notice(published_at DESC, id DESC) WHERE enabled = TRUE;

CREATE TABLE notice_target (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notice_id BIGINT NOT NULL REFERENCES notice(id) ON DELETE CASCADE,
    page VARCHAR(50) NOT NULL CHECK (CHAR_LENGTH(TRIM(page)) > 0),
    conditions JSONB NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(conditions) = 'object')
);
CREATE INDEX idx_notice_target_page_notice ON notice_target(page, notice_id);
-- FK cascade and per-notice target replacement must also work without a page predicate.
CREATE INDEX idx_notice_target_notice ON notice_target(notice_id);

COMMIT;
